--[[
	Application Center — server.
	Generated by the Roleplay System dashboard. Keep this Script in ServerScriptService:
	it holds the API key, which must never be placed in a LocalScript or ReplicatedStorage.

	Nothing about the applications is stored in this place. Every time a player opens the
	center, the questions are fetched from the API, so edits in the dashboard show up here
	without republishing.
]]

local HttpService = game:GetService("HttpService")
local Players = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local API_URL = "__API_URL__"
local API_KEY = "__API_KEY__"

local CACHE_SECONDS = 20 -- how long fetched applications are reused before asking the API again
local SUBMIT_COOLDOWN = 10

local folder = Instance.new("Folder")
folder.Name = "ApplicationCenter"
local getApplications = Instance.new("RemoteFunction")
getApplications.Name = "GetApplications"
getApplications.Parent = folder
local submitApplication = Instance.new("RemoteFunction")
submitApplication.Name = "Submit"
submitApplication.Parent = folder
folder.Parent = ReplicatedStorage

local function request(method, path, body)
	local ok, response = pcall(function()
		return HttpService:RequestAsync({
			Url = API_URL .. path,
			Method = method,
			Headers = { ["Content-Type"] = "application/json", ["X-Api-Key"] = API_KEY },
			Body = body and HttpService:JSONEncode(body) or nil,
		})
	end)
	if not ok then
		warn("[ApplicationCenter] request failed:", response)
		return false, { error = "Could not reach the application server. Is 'Allow HTTP Requests' enabled?" }
	end
	local decoded, data = pcall(HttpService.JSONDecode, HttpService, response.Body)
	if not decoded or type(data) ~= "table" then
		data = {}
	end
	return response.Success, data
end

local cache, cachedAt = nil, 0

getApplications.OnServerInvoke = function()
	if cache and os.clock() - cachedAt < CACHE_SECONDS then
		return cache
	end
	local ok, data = request("GET", "/v1/game/applications")
	if not ok then
		return { ok = false, error = data.error or "Could not load applications." }
	end
	cache = { ok = true, group = data.group, applications = data.applications or {} }
	cachedAt = os.clock()
	return cache
end

-- Only plain strings, numbers and lists of strings are forwarded; the API validates everything again.
local function cleanAnswers(raw)
	local out = {}
	if type(raw) ~= "table" then
		return out
	end
	local count = 0
	for key, value in raw do
		count += 1
		if count > 80 or type(key) ~= "string" or #key > 20 then
			continue
		end
		if type(value) == "string" then
			out[key] = string.sub(value, 1, 4000)
		elseif type(value) == "number" then
			out[key] = value
		elseif type(value) == "table" then
			local list = {}
			for i = 1, math.min(#value, 25) do
				if type(value[i]) == "string" then
					table.insert(list, string.sub(value[i], 1, 120))
				end
			end
			out[key] = list
		end
	end
	return out
end

local lastSubmit = {}

submitApplication.OnServerInvoke = function(player, applicationId, answers)
	if type(applicationId) ~= "string" or not string.match(applicationId, "^[%w_-]+$") or #applicationId > 40 then
		return { ok = false, error = "Unknown application." }
	end
	local now = os.clock()
	if lastSubmit[player] and now - lastSubmit[player] < SUBMIT_COOLDOWN then
		return { ok = false, error = "Please wait a few seconds before submitting again." }
	end
	lastSubmit[player] = now

	-- The player's identity comes from the server, so it cannot be spoofed by the client.
	local ok, data = request("POST", "/v1/game/applications/" .. applicationId .. "/submit", {
		userId = player.UserId,
		username = player.Name,
		answers = cleanAnswers(answers),
	})
	if not ok then
		return { ok = false, error = data.error or "Your application could not be submitted." }
	end
	return { ok = true, message = data.message or "Your application has been submitted." }
end

Players.PlayerRemoving:Connect(function(player)
	lastSubmit[player] = nil
end)
